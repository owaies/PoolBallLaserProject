"""
Script to generate dataset statistics across all splits (train/valid/test)
and save to 'docs/data_statistics.md'.
"""
import os
import sys
from pathlib import Path

# Paths
BASE_DIR = Path(__file__).resolve().parent.parent
DATASETS_DIR = BASE_DIR / 'datasets'
DOCS_DIR = BASE_DIR / 'docs'

def generate_summary():
    splits = ['train', 'valid', 'test']
    split_stats = {}
    total_images = 0
    total_labels = 0
    global_class_counts = {}

    for split in splits:
        img_dir = DATASETS_DIR / split / 'images'
        lbl_dir = DATASETS_DIR / split / 'labels'
        
        num_images = len(list(img_dir.glob('*.*'))) if img_dir.exists() else 0
        num_labels = len(list(lbl_dir.glob('*.txt'))) if lbl_dir.exists() else 0
        
        total_images += num_images
        total_labels += num_labels
        
        class_counts = {}
        if lbl_dir.exists():
            for label_file in lbl_dir.glob('*.txt'):
                with open(label_file, 'r') as f:
                    for line in f:
                        parts = line.strip().split()
                        if parts:
                            cls = parts[0]
                            class_counts[cls] = class_counts.get(cls, 0) + 1
                            global_class_counts[cls] = global_class_counts.get(cls, 0) + 1
                            
        split_stats[split] = {
            'images': num_images,
            'labels': num_labels,
            'boxes': sum(class_counts.values()),
            'class_counts': class_counts
        }

    # Class mappings
    class_names = {
        "0": "cue_ball",
        "1": "1_ball", "2": "2_ball", "3": "3_ball", "4": "4_ball",
        "5": "5_ball", "6": "6_ball", "7": "7_ball", "8": "8_ball",
        "9": "9_ball", "10": "10_ball", "11": "11_ball", "12": "12_ball",
        "13": "13_ball", "14": "14_ball", "15": "15_ball"
    }

    report_content = f"""# Dataset Statistics

This file is automatically generated by `scripts/dataset_summary.py`.

## Overview
- **Total Combined Images:** {total_images}
- **Total Bounding Boxes:** {sum(global_class_counts.values())}

### Splits
| Split | Images | Labels | Bounding Boxes |
|---|---|---|---|
| **Train** | {split_stats['train']['images']} | {split_stats['train']['labels']} | {split_stats['train']['boxes']} |
| **Valid** | {split_stats['valid']['images']} | {split_stats['valid']['labels']} | {split_stats['valid']['boxes']} |
| **Test** | {split_stats['test']['images']} | {split_stats['test']['labels']} | {split_stats['test']['boxes']} |
| **Total** | {total_images} | {total_labels} | {sum(global_class_counts.values())} |

## Class Distribution (All Splits Combined)
| Class ID | Class Name | Instance Count |
|---|---|---|
"""
    for cls_id in sorted(global_class_counts.keys(), key=int):
        name = class_names.get(cls_id, f"Unknown ({cls_id})")
        count = global_class_counts[cls_id]
        report_content += f"| {cls_id} | {name} | {count} |\n"

    report_content += """
## Notes
- **Data Harmonization:** Bounding boxes from multiple sources (Roboflow and GitHub Snooker) were mapped to a unified 16-class representation: class `0` is `cue_ball` (or snooker white ball), and classes `1-15` represent the standard solid/striped pool balls.
- **Filtering:** Non-ball objects (e.g., table racks, cue sticks) and classification-only datasets (which lacked bounding boxes) were skipped to optimize YOLO object detection performance.
"""

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    report_path = DOCS_DIR / 'data_statistics.md'
    
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write(report_content)
        
    print(f"Summary generated and saved to {report_path}")

if __name__ == '__main__':
    generate_summary()
